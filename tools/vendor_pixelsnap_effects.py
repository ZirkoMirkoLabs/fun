"""Rebuild pinned effects bundles from audited local upstream checkouts (Node + esbuild).

Usage: python tools/vendor_pixelsnap_effects.py PIXELFX_CHECKOUT GIFENC_CHECKOUT
No fetching, installs or publication. Generated bytes are recorded in vendor-manifest.json.
"""
from pathlib import Path
import hashlib
import json
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
FX_IDS = '''arcane/arcane-orb arcane/portal arcane/rune-circle
explosions/firework-burst explosions/small-explosion explosions/smoke-bomb
fire/campfire fire/candle fire/torch
ice/ice-crystal ice/snowflake-burst impacts/hit-spark
lightning/ball-lightning lightning/lightning-strike
nature/healing-bloom nature/poison-cloud pickups/collect-burst
water/bubbles water/ripples water/splash
weather/fireflies weather/rain weather/snow ui/confetti'''.split()

def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')

def main():
    fx, gif = map(Path, sys.argv[1:])
    rev = subprocess.check_output(['git', '-C', str(fx), 'rev-parse', 'HEAD'], text=True).strip()
    gifrev = subprocess.check_output(['git', '-C', str(gif), 'rev-parse', 'HEAD'], text=True).strip()
    dest = ROOT/'projects/pixelsnap/vendor/pixelfx-0.2.0'
    entry = fx/'pixelsnap-entry.mjs'
    write(entry, '\n'.join(f'import * as fx{i} from "./src/fx/{id}.js";' for i,id in enumerate(FX_IDS)) +
          '\nexport const modules={'+','.join(f'"{id}":fx{i}' for i,id in enumerate(FX_IDS))+'};\n'+
          'export {createFrame,createFx,composite} from "./src/core/index.js";\n')
    builder = fx/'pixelsnap-build.mjs'
    gif_entry = gif/'pixelsnap-entry.mjs'
    # Only the MIT GIF writer. Do not bundle its separately derived PNN quantizer.
    write(gif_entry, 'export {GIFEncoder} from "./src/index.js";\n')
    write(builder, 'import {build} from "esbuild";\n'+
          f'await build({json.dumps(dict(entryPoints=[str(entry)],outfile=str(dest/"pixelfx.mjs"),bundle=True,minify=True,format="esm",legalComments="inline"))});\n'+
          f'await build({json.dumps(dict(entryPoints=[str(gif_entry)],outfile=str(ROOT/"projects/pixelsnap/vendor/gifenc-1.0.3/gifenc.mjs"),bundle=True,minify=True,format="esm",legalComments="inline"))});\n'+
          'const {modules}=await import("./pixelsnap-entry.mjs");\n'+
          'const {writeFileSync}=await import("node:fs");\n'+
          'const catalog=Object.entries(modules).map(([id,{meta}])=>({id,name:meta.name,description:meta.desc,category:id.split("/")[0],duration:meta.duration,loop:!!meta.loop}));\n'+
          f'writeFileSync({json.dumps(str(ROOT/"projects/pixelsnap/effects-catalog.json"))},JSON.stringify(catalog,null,2)+"\\n");\n')
    subprocess.run(['node',str(builder)],check=True)
    write(dest/'LICENSE.txt',(fx/'LICENSE').read_text())
    write(dest/'NOTICE.txt',(fx/'NOTICE.md').read_text()+'\nPixelSnap imports code only; Patch Pixel font and gallery assets are NOT included.\n')
    gd=ROOT/'projects/pixelsnap/vendor/gifenc-1.0.3'
    write(gd/'LICENSE.txt',(gif/'LICENSE.md').read_text())
    write(gd/'NOTICE.txt','GIF writer only; PNN quantizer excluded. Original LZW acknowledgements:\n'+
          (gif/'src/lzwEncode.js').read_text().split('*/',1)[0]+'*/\n')
    manifest=json.loads((ROOT/'vendor-manifest.json').read_text())
    manifest['files']=[f for f in manifest['files'] if not f['path'].startswith(('pixelsnap/vendor/pixelfx-','pixelsnap/vendor/gifenc-'))]
    for folder,repo,version,commit in [(dest,'patch-gg/pixelfx','0.2.0',rev),(gd,'mattdesl/gifenc','1.0.3',gifrev)]:
        for p in sorted(folder.iterdir()):
            manifest['files'].append(dict(path=p.relative_to(ROOT/'projects').as_posix(),package=repo,version=version,
                sha256=hashlib.sha256(p.read_bytes()).hexdigest(),source=f'https://github.com/{repo}/tree/{commit}',
                note='Local esbuild bundle of pinned source; licence retained. Rebuild with tools/vendor_pixelsnap_effects.py.'))
    write(ROOT/'vendor-manifest.json',json.dumps(manifest,indent=2)+'\n')
    print(f'Vendored {len(FX_IDS)} effects from {rev}; gifenc {gifrev}.')

if __name__=='__main__': main()
